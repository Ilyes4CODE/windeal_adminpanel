const I18n = {
  current: localStorage.getItem(AppConfig.LANG_KEY) || AppConfig.DEFAULT_LANG,
  t(key) {
    return Translations[this.current]?.[key] || Translations.en[key] || key;
  },
  set(lang) {
    this.current = lang;
    localStorage.setItem(AppConfig.LANG_KEY, lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = I18n.t(key);
      } else {
        el.textContent = I18n.t(key);
      }
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(el => {
      el.placeholder = I18n.t(el.getAttribute("data-i18n-ph"));
    });
    document.querySelectorAll(".lang-btn").forEach(b => b.classList.remove("active"));
    document.querySelector(`.lang-btn[data-lang="${lang}"]`)?.classList.add("active");
  },
};
